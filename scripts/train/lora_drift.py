def rel(p):
    return el.rel(p)


def make(args):
    src = el.at_root(args.real_cache)
    idx = json.load(open(os.path.join(src, "index.json"), encoding="utf-8"))
    meta = idx["meta"]
    if args.caption not in meta["styles"]:
        raise SystemExit("%s has captions %s, asked for %s" % (rel(src), meta["styles"], args.caption))
    clips = [dict(c) for c in idx["clips"] if c["pool"] in args.pools]
    if args.limit:
        clips = [c for p in args.pools for c in el.spaced([x for x in clips if x["pool"] == p], args.limit)]
    out_dir = el.at_root(args.out or D0 % args.caption)
    if os.path.isfile(os.path.join(out_dir, "index.json")) and not args.force:
        raise SystemExit("%s already holds a D0 cache; pass --force to rebuild it" % rel(out_dir))
    torch.manual_seed(args.seed)
    t0 = time.perf_counter()
    sam = el.load_model()
    n_audio, frames, ds = el.sizes(sam, meta["gen_s"], meta["pad_s"])
    if frames != meta["latent_frames"]:
        raise SystemExit("model gives %d latent frames, the real cache has %d" % (frames, meta["latent_frames"]))
    n_gen = int(round(meta["gen_s"] * SR))
    src_s = float(args.source_s or meta["gen_s"])
    report = {"pools": {"generated": dict(Counter(c["pool"] for c in clips))}, "excluded": []}
    kept, lat, listen = [], [], []
    drop = ("row", "src", "src_sr", "src_frames", "src_channels", "clipped_frac", "gain_db", "content_samples",
            "content_frames", "window_start_s", "padded", "username", "url", "freesound_id", "license")
    print("D0: %d clips from %s, %d steps %s cfg %.1f, source %.2f s, captions %s" % (
        len(clips), rel(src), args.steps, args.sampler, args.cfg, src_s, args.caption), flush=True)
    for b in range(0, len(clips), args.batch):
        chunk = clips[b:b + args.batch]
        seed = int(args.seed) + b // args.batch
        with torch.no_grad():
            a = sam.generate(prompt=[c["captions"][args.caption] for c in chunk], duration=src_s, steps=args.steps,
                             cfg_scale=args.cfg, batch_size=len(chunk), seed=seed, sampler_type=args.sampler,
                             duration_padding_sec=meta["pad_s"], disable_tqdm=True)
        a = a.to(torch.float32).cpu().numpy()
        wins, ents = [], []
        for j, (c, x) in enumerate(zip(chunk, a)):
            w, info = el.prep(x, SR, n_gen, meta["preroll_s"])
            e = {k: v for k, v in c.items() if k not in drop}
            e.update(info)
            e.update({"audio": "generated", "seed": seed, "batch_pos": j, "license": "generated by %s" % el.MODEL})
            if w is None:
                report["excluded"].append({"dataset": "generated", "id": c["id"], "pool": c["pool"], "reason": "silent"})
                continue
            e["content_frames"] = int(-(-e["content_samples"] // ds))
            wins.append(w)
            ents.append(e)
            if len(listen) < args.listen:
                listen.append(w.mean(axis=0))
        if wins:
            lat.append(el.encode_audio(sam, wins, n_audio))
            kept.extend(ents)
        if (b // args.batch + 1) % 25 == 0:
            print("  generated %d/%d  %.1f s" % (min(b + args.batch, len(clips)), len(clips), time.perf_counter() - t0),
                  flush=True)
    z = torch.cat(lat, 0)
    texts, uniq = el.text_tables(sam, kept, [args.caption], meta["gen_s"], args.text_bs)
    m2 = dict(meta)
    m2.update({"audio": "generated", "styles": [args.caption], "real_cache": rel(src), "latent_shape": list(z.shape),
               "text": uniq, "out": rel(out_dir), "seconds": round(time.perf_counter() - t0, 1),
               "generated_by": {"model": el.MODEL, "steps": args.steps, "sampler": args.sampler, "cfg_scale": args.cfg,
                                "duration_s": src_s, "duration_padding_s": meta["pad_s"], "batch": args.batch,
                                "seed": args.seed, "precision": "fp16", "caption": args.caption},
               "processing": "small-sfx generate at the settings in generated_by, then the real-pool chain: " +
                             meta.get("processing", "")})
    el.save_cache(out_dir, kept, z, texts, m2, report)
    if listen:
        gap = np.zeros(int(0.25 * SR), np.float32)
        y = np.concatenate([v for x in listen for v in (x, gap)])
        y = y / max(1e-9, float(np.abs(y).max())) * 0.9
        wavfile.write(os.path.join(out_dir, "listen_%d.wav" % len(listen)), SR, (y * 32767).astype(np.int16))
    print("D0 cache: %d clips (%s), %d silent, latents %s, %.1f s" % (
        len(kept), ", ".join("%s %d" % x for x in sorted(Counter(e["pool"] for e in kept).items())),
        len(report["excluded"]), tuple(z.shape), time.perf_counter() - t0))
    print("saved -> %s" % rel(out_dir))
    del sam
    lr.free_gpu("D0 generation")
    return 0


def train(args):
    like = el.at_root(args.like)
    cp = os.path.join(like, "config.json")
    if not os.path.isfile(cp):
        raise SystemExit("%s has no config.json from lora_real.py train" % rel(like))
    saved = json.load(open(cp, encoding="utf-8"))["args"]
    ns = argparse.Namespace(**saved)
    ns.cache = args.cache or D0 % saved["caption"]
    ns.name = args.name or "d0_%s" % os.path.basename(os.path.normpath(like))
    ns.out = None
    ns.resume = bool(args.resume)
    for k in ("steps", "seed"):
        v = getattr(args, k)
        if v is not None:
            setattr(ns, k, v)
    idx = json.load(open(os.path.join(el.at_root(ns.cache), "index.json"), encoding="utf-8"))
    if idx["meta"].get("audio") != "generated":
        raise SystemExit("%s holds %s audio; the D0 run trains on generated clips" % (ns.cache, idx["meta"].get("audio")))
    print("D0 recipe from %s, cache %s, run %s" % (rel(like), ns.cache, ns.name), flush=True)
    lr.train(ns)
    return 0


def mel_fb():
    hz = lambda m: 700.0 * (10.0 ** (m / 2595.0) - 1.0)
    mel = lambda f: 2595.0 * np.log10(1.0 + f / 700.0)
    pts = hz(np.linspace(mel(20.0), mel(SR / 2.0), N_MELS + 2))
    f = np.fft.rfftfreq(N_FFT, 1.0 / SR)
    fb = np.zeros((N_MELS, len(f)))
    for i in range(N_MELS):
        lo, c, hi = pts[i:i + 3]
        fb[i] = np.clip(np.minimum((f - lo) / (c - lo), (hi - f) / (hi - c)), 0.0, None)
    return fb


def mel_db(x, fb, win):
    y = np.pad(np.asarray(x, dtype=np.float64), (N_FFT // 2, N_FFT // 2))
    fr = np.lib.stride_tricks.sliding_window_view(y, N_FFT)[::HOP] * win
    m = 10.0 * np.log10(fb @ (np.abs(np.fft.rfft(fr, axis=1)) ** 2).T + 1e-10)
    return np.maximum(m, m.max() - 80.0)


def ratio_ci(paired, spread, reps, seed):
    p, s = np.asarray(paired), np.asarray(spread)
    rng = np.random.default_rng(seed)
    ix = rng.integers(0, len(p), size=(reps, len(p)))
    r = np.median(p[ix], axis=1) / np.maximum(np.median(s[ix], axis=1), 1e-9)
    return [float(np.percentile(r, 2.5)), float(np.percentile(r, 97.5))]


def route_info(path, prompts, steps):
    head = {"steps": steps, "prompts": prompts}
    if path is None:
        return {**head, "clusters": [], "sources": [],
                "note": "small-sfx base weights through the production StableAudio3Generator, no real audio"}
    src = lr.lora_sources(path)
    if src["audio"] == "real":
        note = ("LoRA merged into small-sfx, trained on %d real clips of the train and val pools of %s; clusters and "
                "sources list every one of them" % (src["clips"], src["cache"]))
    else:
        note = ("D0 control: LoRA merged into small-sfx, trained on %d small-sfx generations from the captions of the "
                "listed training-side clips (cache %s); no real audio" % (src["clips"], src["cache"]))
    return {**head, "clusters": src["clusters"], "sources": src["sources"], "lora": rel(el.at_root(path)),
            "cache": src["cache"], "audio": src["audio"], "note": note}


def gen_arm(name, path, keys, args):
    from sarge.generators.stable_audio3 import StableAudio3Generator
    from sarge.types import CacheKey
    lr.install_hook(path, args.strength)
    g = StableAudio3Generator(sampler_type="euler", steps=args.steps)
    g.ensure_ready()
    d = os.path.join(el.at_root(args.out_dir), name)
    os.makedirs(d, exist_ok=True)
    g.generate(CacheKey(keys[0][0], keys[0][1], INTENSITY), variant=0)
    clips, retried, prompts, ms = {}, {}, {}, []
    for et, mat in keys:
        k = CacheKey(et, mat, INTENSITY)
        kn = "%s|%s" % (et, mat)
        prompts[kn] = g._prompt(k)
        xs, rs = [], []
        for v in range(args.seeds):
            r0 = g.static_stats.get("static_retries", 0)
            t0 = time.perf_counter()
            c = g.generate(k, variant=v)
            ms.append((time.perf_counter() - t0) * 1000.0)
            rs.append(bool(g.static_stats.get("static_retries", 0) > r0))
            c.to_wav(os.path.join(d, "%s-%s_%02d.wav" % (et, mat, v)))
            xs.append(np.asarray(c.samples, dtype=np.float32))
        clips[kn], retried[kn] = xs, rs
    json.dump(route_info(path, prompts, args.steps), open(os.path.join(d, "route.json"), "w", encoding="utf-8"),
              indent=1)
    info = {"lora": getattr(g._model, "lora", None), "ms_median": float(np.median(ms)), "route": rel(d),
            "fast_stats": g.fast_stats() if hasattr(g, "fast_stats") else {}, "static": dict(g.static_stats),
            "retried_seeds": int(sum(sum(r) for r in retried.values()))}
    k0 = CacheKey(keys[0][0], keys[0][1], INTENSITY)
    again = [np.asarray(g.generate(k0, variant=v).samples, dtype=np.float32) for v in range(min(3, args.seeds))]
    info["repeat_max_abs"] = float(max(np.max(np.abs(a - b)) for a, b in zip(again, clips["%s|%s" % keys[0]])))
    del g
    lr.install_hook(None)
    lr.free_gpu("arm %s" % name)
    return clips, retried, info


def static_rate(xs):
    from sarge.static_guard import is_static
    return float(np.mean([is_static(x, SR)[0] for x in xs]))


def shape_medians(xs):
    import vocab_eval
    rows = vocab_eval.shape_rows(xs)
    return {f: float(np.nanmedian([r[f] for r in rows])) for f in SHAPE}


def pair_stats(pa, sp, args):
    if not pa:
        return {"paired_db": NAN, "ratio": NAN, "ratio_ci": [NAN, NAN], "pairs": 0}
    return {"paired_db": float(np.median(pa)), "ratio": float(np.median(pa) / max(np.median(sp), 1e-9)),
            "ratio_ci": ratio_ci(pa, sp, args.boot, args.boot_seed), "pairs": len(pa)}


def compare(base, rb, arms, ra, keys, args):
    fb, win = mel_fb(), np.hanning(N_FFT)
    mels = {name: {k: [mel_db(x, fb, win) for x in xs] for k, xs in clips.items()} for name, clips in
            [("base", base)] + list(arms.items())}
    per = {}
    for k in ["%s|%s" % kk for kk in keys]:
        mb = mels["base"][k]
        n = len(mb)
        spread = [float(np.mean(np.abs(mb[i] - mb[(i + 1) % n]))) for i in range(n)]
        row = {"seed_db": float(np.median(spread)), "spread": spread, "static_base": static_rate(base[k]),
               "retried_base": rb[k], "shape_base": shape_medians(base[k])}
        for name in arms:
            ma = mels[name][k]
            ok = [i for i in range(n) if not rb[k][i] and not ra[name][k][i]]
            paired = {i: float(np.mean(np.abs(mb[i] - ma[i]))) for i in ok}
            row[name] = {**pair_stats([paired[i] for i in ok], [spread[i] for i in ok], args), "paired": paired,
                         "retried": ra[name][k], "static": static_rate(arms[name][k]),
                         "shape": shape_medians(arms[name][k])}
        per[k] = row
    groups = {"gate": [("footstep|%s" % m, v) for m in GATE_MATS for v in range(min(GATE_VARIANTS, args.seeds))
                       if "footstep|%s" % m in per],
              "vocab": [(k, v) for k in per for v in range(args.seeds)]}
    pooled = {}
    for gname, items in groups.items():
        pooled[gname] = {"clips": len(items)}
        for name in arms:
            it = [(k, v) for k, v in items if v in per[k][name]["paired"]]
            pooled[gname][name] = {**pair_stats([per[k][name]["paired"][v] for k, v in it],
                                                [per[k]["spread"][v] for k, v in it], args),
                                   "seed_db": float(np.median([per[k]["spread"][v] for k, v in items]))
                                   if items else NAN}
    return per, pooled


def drift_report(per, pooled, infos, arms, args):
    W = 140
    L = []
    L.append("=" * W)
    L.append(" LORA DRIFT at the production tier (StableAudio3Generator euler, %d steps, cfg 2.0, fp16, accelerator, "
             "hoist and static guard, 1.0 s generation kept at 0.6 s, seeds 0 to %d through seed_for)" % (
                 args.steps, args.seeds - 1))
    L.append(" drift ratio = median over seeds of the log-mel L1 distance between the base clip and the LoRA clip of "
             "the same seed, over the median distance between two base seeds of the same key; 0 = unchanged, 1 = as "
             "far as a new seed; seeds the static guard retried in either arm leave the pairs; 95%% interval from %d "
             "seed resamples" % args.boot)
    L.append("=" * W)
    for name, info in infos.items():
        lo = info.get("lora") or {}
        L.append(" arm %-10s %s  %.1f ms/clip  retried %d  repeat max abs %.2e  graphs %s eager %s hoisted %s  -> %s" % (
            name, lo.get("path", "base weights"), info["ms_median"], info["retried_seeds"], info["repeat_max_abs"],
            info["fast_stats"].get("graphs"), info["fast_stats"].get("eager"), info["fast_stats"].get("hoisted"),
            info["route"]))
    L.append("-" * W)
    for gname in ("gate", "vocab"):
        p = pooled.get(gname, {})
        L.append(" %-6s %4d clips  %s" % (gname, p.get("clips", 0), "   ".join(
            "%s ratio %.2f [%.2f,%.2f] (%.2f / %.2f dB, %d pairs)" % (
                name, p[name]["ratio"], p[name]["ratio_ci"][0], p[name]["ratio_ci"][1], p[name]["paired_db"],
                p[name]["seed_db"], p[name]["pairs"]) for name in arms if name in p)))
    L.append("-" * W)
    L.append(" %-20s %8s  %-27s %s" % ("key", "seed dB", "base static attack/tail/floor", "   ".join(
        "%-40s" % ("%s ratio, static, attack/tail/floor" % n) for n in arms)))
    for k, row in per.items():
        sb = row["shape_base"]
        cells = []
        for name in arms:
            r = row[name]
            sh = r["shape"]
            cells.append("%5.2f [%.2f,%.2f] st %.2f %5.1f/%4.0f/%6.1f" % (
                r["ratio"], r["ratio_ci"][0], r["ratio_ci"][1], r["static"], sh["attack_ms"], sh["tail_ms"],
                sh["floor_db"]))
        L.append(" %-20s %8.2f  st %.2f %5.1f/%4.0f/%6.1f      %s" % (
            k, row["seed_db"], row["static_base"], sb["attack_ms"], sb["tail_ms"], sb["floor_db"], "   ".join(cells)))
    L.append("-" * W)
    L.append(" each arm folder is a vocab_eval route: --route NAME=%s/NAME (route.json lists the training clusters)" %
             rel(el.at_root(args.out_dir)))
    L.append("=" * W)
    return L


def drift(args):
    import vocab_eval
    keys = [(et, mat) for et, mat, _t in vocab_eval.KEYS]
    arms_spec = []
    for spec in args.lora:
        name, _, p = spec.partition("=")
        if not ARM_NAME.fullmatch(name or "") or not p or name == "base":
            raise SystemExit("--lora takes NAME=PATH, NAME of letters, digits and _ . + - other than base, got %r"
                             % spec)
        arms_spec.append((name, p))
    t0 = time.perf_counter()
    base, rb, info_b = gen_arm("base", None, keys, args)
    infos = {"base": info_b}
    arms, ra = {}, {}
    for name, p in arms_spec:
        arms[name], ra[name], infos[name] = gen_arm(name, p, keys, args)
    per, pooled = compare(base, rb, arms, ra, keys, args)
    lines = drift_report(per, pooled, infos, arms, args)
    print("\n".join(lines))
    out = el.at_root(args.report)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out + ".txt", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    with open(out + ".json", "w", encoding="utf-8") as fh:
        json.dump({"meta": {"args": vars(args), "keys": ["%s|%s" % k for k in keys], "seconds":
                            round(time.perf_counter() - t0, 1), "mel": {"n_fft": N_FFT, "hop": HOP, "n_mels": N_MELS},
                            "gate": {"materials": GATE_MATS, "variants": GATE_VARIANTS}},
                   "arms": infos, "pooled": pooled, "per_key": per}, fh, indent=1)
    print("saved -> %s.json" % rel(out))
    return 0


def parse(argv):
    ap = argparse.ArgumentParser(description="D0 control for the LoRA route: the same recipe on clips small-sfx made "
                                             "itself, and the drift of production 3-step output.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("make")
    m.add_argument("--real-cache", default=el.OUT)
    m.add_argument("--caption", default="sarge", choices=list(el.STYLES))
    m.add_argument("--out", default=None)
    m.add_argument("--pools", nargs="+", default=["train", "val"], choices=["train", "val"])
    m.add_argument("--steps", type=int, default=3)
    m.add_argument("--sampler", default="euler")
    m.add_argument("--cfg", type=float, default=2.0)
    m.add_argument("--source-s", type=float, default=None)
    m.add_argument("--batch", type=int, default=16)
    m.add_argument("--text-bs", type=int, default=16)
    m.add_argument("--seed", type=int, default=0)
    m.add_argument("--limit", type=int, default=None)
    m.add_argument("--listen", type=int, default=24)
    m.add_argument("--force", action="store_true")
    t = sub.add_parser("train")
    t.add_argument("--like", required=True)
    t.add_argument("--cache", default=None)
    t.add_argument("--name", default=None)
    t.add_argument("--steps", type=int, default=None)
    t.add_argument("--seed", type=int, default=None)
    t.add_argument("--resume", action="store_true")
    d = sub.add_parser("drift")
    d.add_argument("--lora", action="append", default=[], required=True)
    d.add_argument("--strength", type=float, default=1.0)
    d.add_argument("--steps", type=int, default=3)
    d.add_argument("--seeds", type=int, default=20)
    d.add_argument("--boot", type=int, default=2000)
    d.add_argument("--boot-seed", type=int, default=0)
    d.add_argument("--out-dir", default=DRIFT_DIR)
    d.add_argument("--report", default=REPORT)
    return ap.parse_args(argv)


def main(argv=None):
    args = parse(argv)
    return {"make": make, "train": train, "drift": drift}[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
